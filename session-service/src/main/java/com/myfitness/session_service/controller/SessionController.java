package com.myfitness.session_service.controller;

import com.myfitness.session_service.dto.CreateSessionRequest;
import com.myfitness.session_service.dto.SessionResponse;
import com.myfitness.session_service.dto.SessionSummaryResponse;
import com.myfitness.session_service.service.SessionService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springdoc.core.annotations.ParameterObject;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.http.HttpStatus;
import org.springframework.web.bind.annotation.*;

import java.util.UUID;

@RestController
@RequestMapping("/api/v1/sessions")
@RequiredArgsConstructor
@Tag(name = "Workout Sessions", description = "Endpoints for managing workout sessions, tracking live exercise sets, and retrieving training history")
public class SessionController {

    private final SessionService sessionService;

    // CREATE -> POST /api/v1/sessions
    @Operation(
            summary = "Create a new workout session",
            description = "Saves a complete workout session including all exercises and sets performed. Protected by Idempotency-Key to prevent duplicate saves on network retries."
    )
    @ApiResponses({
            @ApiResponse(responseCode = "201", description = "Session created successfully"),
            @ApiResponse(responseCode = "400", description = "Invalid request data or validation error")
    })
    @PostMapping
    @ResponseStatus(HttpStatus.CREATED)
    public void createSession(
            @Parameter(description = "UUID generated by the frontend to guarantee idempotency", required = true)
            @RequestHeader("Idempotency-Key") String idempotencyKey,
            @RequestHeader("X-User-Email") String userEmail,
            @Valid @RequestBody CreateSessionRequest request) {

        sessionService.saveSession(userEmail, request);
    }

    // GET ALL (PAGINATED SUMMARY) -> GET /api/v1/sessions
    @Operation(
            summary = "Get all user sessions (Paginated Summary)",
            description = "Retrieves a lightweight paginated list of all workout sessions for the user's history, excluding heavy nested exercise/set lists."
    )
    @ApiResponses({
            @ApiResponse(responseCode = "200", description = "Paginated summary of sessions retrieved successfully")
    })
    @GetMapping
    @ResponseStatus(HttpStatus.OK)
    public Page<SessionSummaryResponse> getAllUserSessions(
            @RequestHeader("X-User-Email") String userEmail,
            @ParameterObject Pageable pageable) {

        return sessionService.getAllUserSessions(userEmail, pageable);
    }

    // GET BY ID (DETAILED) -> GET /api/v1/sessions/{id}
    @Operation(
            summary = "Get detailed session by ID",
            description = "Retrieves the full details of a specific workout session, including all exercises, sets, weights, and reps performed."
    )
    @ApiResponses({
            @ApiResponse(responseCode = "200", description = "Session detail found and returned"),
            @ApiResponse(responseCode = "404", description = "Session not found or does not belong to the user")
    })
    @GetMapping("/{id}")
    @ResponseStatus(HttpStatus.OK)
    public SessionResponse getUserSessionById(
            @RequestHeader("X-User-Email") String userEmail,
            @Parameter(description = "Unique identifier (UUID) of the session", required = true)
            @PathVariable UUID id) {

        return sessionService.getUserSessionById(userEmail, id);
    }

    // DELETE -> DELETE /api/v1/sessions/{id}
    @Operation(
            summary = "Delete a session",
            description = "Permanently deletes a workout session and all its nested exercises and sets from the history."
    )
    @ApiResponses({
            @ApiResponse(responseCode = "204", description = "Session deleted successfully"),
            @ApiResponse(responseCode = "404", description = "Session not found")
    })
    @DeleteMapping("/{id}")
    @ResponseStatus(HttpStatus.NO_CONTENT)
    public boolean deleteSession(
            @RequestHeader("X-User-Email") String userEmail,
            @Parameter(description = "Unique identifier (UUID) of the session to delete", required = true)
            @PathVariable UUID id) {

        return sessionService.deleteSession(userEmail, id);
    }
}